ALTER TABLE spring_session ALTER COLUMN principal_name TYPE varchar(254);
CREATE TABLE password_reset_token(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,token_hash varchar(64) UNIQUE NOT NULL,user_id bigint NOT NULL REFERENCES user_account(id),expires_at timestamptz NOT NULL,used boolean NOT NULL DEFAULT false);
CREATE INDEX reset_user ON password_reset_token(user_id);
